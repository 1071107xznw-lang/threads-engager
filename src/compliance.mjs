// 掃一段文字，回傳命中的法規風險。空陣列＝沒掃到（不代表一定安全，只代表沒踩到已知紅線）。
export function scanCompliance(text) {
  const s = String(text ?? '');
  if (!s.trim()) return [];
  const hits = [];
  for (const t of RISK_TERMS) {
    const m = s.match(t.pattern);
    if (m) hits.push({ term: m[0], label: t.label, law: t.law, fine: t.fine });
  }
  return hits;
}

// 一行摘要，給 dashboard 卡片與 CLI log 用。
export function summarizeCompliance(hits) {
  if (!hits || !hits.length) return '';
  return hits
    .map((h) => `「${h.term}」${h.law}${h.fine !== '—' ? `（${h.fine}）` : ''}`)
    .join('；');
}
